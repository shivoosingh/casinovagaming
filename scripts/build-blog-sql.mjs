// Turn the reviewed rewrite batches in supabase/blog-phase2/*.json into one
// idempotent SQL file. Nothing here touches the database: the SQL is applied by
// hand (Supabase SQL editor or `supabase db query --linked -f`) after approval.
//
//   batch-*.json      full rewrites: [{ slug, title, excerpt, content, seo_title, seo_description, tags, needs_review }]
//   meta-fixes.json   small edits: [{ slug, seo_title?, seo_description?, replace?: [[from, to]] }]
//
// Rows are UPDATEs keyed on slug and limited to published posts, so the script
// can never publish a draft, resurrect an archived post or create a new URL.
// Usage: node scripts/build-blog-sql.mjs
import fs from "node:fs";
import path from "node:path";

const DIR = "supabase/blog-phase2";
const OUT = "supabase/blog-seed-2026-11-phase2.sql";
const REVIEW_OUT = "docs/seo/phase2-content-review.md";

/** Dollar-quote with a tag that cannot appear in the text. */
function quote(text) {
  let tag = "t";
  while (text.includes(`$${tag}$`)) tag += "x";
  return `$${tag}$${text}$${tag}$`;
}
const sqlArray = (items) => `ARRAY[${items.map((item) => quote(String(item))).join(", ")}]::text[]`;
const sqlSlug = (slug) => {
  if (!/^[a-z0-9-]+$/.test(slug)) throw new Error(`unsafe slug: ${slug}`);
  return `'${slug}'`;
};

const batchFiles = fs.readdirSync(DIR).filter((f) => /^batch-\d+\.json$/.test(f)).sort();
const rewrites = batchFiles.flatMap((f) => JSON.parse(fs.readFileSync(path.join(DIR, f), "utf8")));
const metaPath = path.join(DIR, "meta-fixes.json");
const metaFixes = fs.existsSync(metaPath) ? JSON.parse(fs.readFileSync(metaPath, "utf8")) : [];

const seen = new Set();
for (const row of rewrites) {
  if (seen.has(row.slug)) throw new Error(`duplicate slug across batches: ${row.slug}`);
  seen.add(row.slug);
  for (const key of ["title", "excerpt", "content", "seo_title", "seo_description"]) {
    if (!row[key] || typeof row[key] !== "string") throw new Error(`${row.slug}: missing ${key}`);
  }
}

const lines = [
  "-- ============================================================================",
  "-- Casinova Gaming blog: phase 2 rewrites. Generated by scripts/build-blog-sql.mjs.",
  "-- Do not edit by hand: change supabase/blog-phase2/*.json and regenerate.",
  `-- ${rewrites.length} full rewrites, ${metaFixes.length} metadata-only fixes.`,
  "-- Idempotent. Updates published rows only; creates, publishes and deletes nothing.",
  "-- ============================================================================",
  "",
  "BEGIN;",
  "",
];
for (const row of rewrites) {
  lines.push(
    `-- ${row.slug}`,
    "UPDATE public.blog_posts SET",
    `  title = ${quote(row.title)},`,
    `  excerpt = ${quote(row.excerpt)},`,
    `  content = ${quote(row.content)},`,
    `  seo_title = ${quote(row.seo_title)},`,
    `  seo_description = ${quote(row.seo_description)},`,
    ...(Array.isArray(row.tags) && row.tags.length ? [`  tags = ${sqlArray(row.tags)},`] : []),
    "  updated_at = now()",
    `WHERE slug = ${sqlSlug(row.slug)} AND status = 'published';`,
    ""
  );
}
for (const fix of metaFixes) {
  const sets = [];
  if (fix.seo_title) sets.push(`  seo_title = ${quote(fix.seo_title)}`);
  if (fix.seo_description) sets.push(`  seo_description = ${quote(fix.seo_description)}`);
  // Exact-text swaps inside the body, for a one-phrase fix that does not justify a rewrite.
  // A column can be assigned once per UPDATE, so several swaps are nested.
  if (fix.replace?.length) {
    const expr = fix.replace.reduce((inner, [from, to]) => `replace(${inner}, ${quote(from)}, ${quote(to)})`, "content");
    sets.push(`  content = ${expr}`, "  updated_at = now()");
  }
  if (!sets.length) continue;
  lines.push(`-- ${fix.slug} (metadata only)`, "UPDATE public.blog_posts SET", sets.join(",\n"), `WHERE slug = ${sqlSlug(fix.slug)} AND status = 'published';`, "");
}
lines.push("COMMIT;", "");
fs.writeFileSync(OUT, lines.join("\n"));

const review = [
  "# Phase 2 blog rewrites: questions for the owner",
  "",
  "Each rewritten post lists what the writer could not verify from the code. Answer these before or after the SQL is applied; none of them blocks the corrections already made.",
  "",
];
for (const row of rewrites) {
  review.push(`## ${row.slug}`, "", `Title: ${row.title}`, "");
  const items = row.needs_review ?? [];
  review.push(...(items.length ? items.map((item) => `- ${item}`) : ["- Nothing flagged."]), "");
}
fs.mkdirSync(path.dirname(REVIEW_OUT), { recursive: true });
fs.writeFileSync(REVIEW_OUT, review.join("\n"));

console.log(`${OUT}: ${rewrites.length} rewrites, ${metaFixes.length} metadata fixes`);
console.log(`${REVIEW_OUT}: ${rewrites.reduce((n, r) => n + (r.needs_review?.length ?? 0), 0)} review items`);
